// ─── Helper to build a Product from seed data ───────────────
function makeProduct(
  index: number,
  handle: string,
  title: string,
  description: string,
  thumbnail: string,
  price: number,
  categorySlug: string,
): Product {
  const categoryId = `cat_${categorySlug}`
  return {
    id: `prod_${handle}`,
    slug: handle,
    name: title,
    description,
    shortDescription: description.slice(0, 80) + '…',
    price,
    currency: 'MAD',
    categoryId,
    collectionId: '',
    images: [{ src: thumbnail, alt: title }],
    options: [
      {
        id: `opt_${handle}_default`,
        title: 'Défaut',
        values: [{ id: `optval_${handle}_std`, value: 'Standard', label: 'Standard' }],
      },
    ],
    variants: [
      {
        id: `var_${handle}_std`,
        sku: `ZS-${handle.toUpperCase().slice(0, 20)}`,
        price,
        inventoryQuantity: 10,
        options: { [`opt_${handle}_default`]: `optval_${handle}_std` },
      },
    ],
    materials: ['Bois'],
    colors: [],
    tags: [],
    featured: index < 6,
    isNew: index >= 10,
    available: true,
    rating: 4 + +(Math.random() > 0.5),
    reviewsCount: Math.floor(Math.random() * 20) + 3,
    sku: `ZS-${handle.toUpperCase().slice(0, 20)}`,
    createdAt: new Date(Date.now() - index * 86400000).toISOString(),
  }
}

